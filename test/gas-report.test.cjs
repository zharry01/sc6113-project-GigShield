// Measures estimated vs. actual gas for every transaction type and writes docs/GAS_REPORT.md
const fs = require("fs");
const path = require("path");
const { ethers } = require("hardhat");
const { time } = require("@nomicfoundation/hardhat-toolbox/network-helpers");

const gUSD = (n) => ethers.parseEther(String(n));
const GWEI_PRICE = 2n; // assumed Sepolia/L1 gas price for the cost column
const ETH_USD = 2500;   // assumed ETH price for the USD column

describe("Gas report (all transaction types)", () => {
  it("writes docs/GAS_REPORT.md", async () => {
    const [admin, auditor, alice] = await ethers.getSigners();
    const rows = [];

    async function measure(label, contract, method, args, signer) {
      const c = contract.connect(signer);
      const estimate = await c[method].estimateGas(...args);
      const receipt = await (await c[method](...args)).wait();
      rows.push({ label, method, estimate, used: receipt.gasUsed });
    }

    const Factory = await ethers.getContractFactory("GigShield");
    const deployEstimate = await ethers.provider.estimateGas(await Factory.getDeployTransaction());
    const shield = await Factory.deploy();
    const deployReceipt = await shield.deploymentTransaction().wait();
    rows.push({ label: "Deploy all 4 contracts", method: "constructor", estimate: deployEstimate, used: deployReceipt.gasUsed });

    const registry = await ethers.getContractAt("RoleRegistry", await shield.registry());
    const token = await ethers.getContractAt("GUSDToken", await shield.token());
    const pool = await ethers.getContractAt("RiskPool", await shield.pool());
    const poolAddr = await pool.getAddress();
    const evidence = ethers.id("demo evidence");

    await measure("Grant Auditor role", registry, "grantRole", [auditor.address, 2], admin);
    await measure("Register as Customer", registry, "registerAsCustomer", [], alice);
    await measure("Faucet (mint 1,000 gUSD)", token, "faucet", [], admin);
    await measure("Approve gUSD to RiskPool", token, "approve", [poolAddr, ethers.MaxUint256], admin);
    await measure("Deposit capital", pool, "deposit", [gUSD(800)], admin);
    await measure("Create product", shield, "createProduct", ["Rider Accident Cover", gUSD(10), gUSD(500), 30], admin);
    await measure("Deactivate product", shield, "setProductActive", [0, false], admin);
    await shield.setProductActive(0, true);
    await token.connect(alice).faucet();
    await token.connect(alice).approve(poolAddr, ethers.MaxUint256);
    await measure("Buy policy", shield, "buyPolicy", [0], alice);
    await measure("File claim", shield, "fileClaim", [0, gUSD(100), evidence], alice);
    await measure("Approve claim + payout", shield, "approveClaim", [0, "Receipt verified"], auditor);
    await measure("File claim (2nd)", shield, "fileClaim", [0, gUSD(50), evidence], alice);
    await measure("Reject claim", shield, "rejectClaim", [1, "Duplicate receipt"], auditor);
    await measure("File claim (3rd)", shield, "fileClaim", [0, gUSD(20), evidence], alice);
    await measure("Withdraw claim", shield, "withdrawClaim", [2], alice);
    await measure("Transfer gUSD", token, "transfer", [auditor.address, gUSD(1)], alice);
    await measure("Withdraw capital", pool, "withdraw", [gUSD(100)], admin);
    await measure("Pause contract", shield, "setPaused", [true], admin);
    await measure("Unpause contract", shield, "setPaused", [false], admin);
    await shield.connect(alice).buyPolicy(0);
    await time.increase(24 * 3600);
    await measure("Cancel policy (pro-rata refund)", shield, "cancelPolicy", [1], alice);
    await measure("Revoke role", registry, "revokeRole", [auditor.address], admin);

    const fmtUsd = (gas) => ((Number(gas) * Number(GWEI_PRICE) * 1e-9) * ETH_USD).toFixed(3);
    const lines = [
      "# Gas Report",
      "",
      `Generated by \`npm run gas\` (Hardhat, solc 0.8.24, optimizer 200 runs). Cost assumes ${GWEI_PRICE} gwei and ETH = $${ETH_USD}.`,
      "",
      "| # | Transaction type | Function | Estimated gas | Actual gas used | Est. cost (USD) |",
      "|---|---|---|---:|---:|---:|",
      ...rows.map((r, i) => `| ${i + 1} | ${r.label} | \`${r.method}\` | ${r.estimate} | ${r.used} | ${fmtUsd(r.used)} |`),
      "",
      "## Optimisations applied",
      "",
      "- **Custom errors** instead of revert strings (smaller bytecode, cheaper reverts).",
      "- **Struct packing**: `Policy` and `Claim` pack `uint64` timestamps, enums, `bool` and `address` into shared slots; amounts use `uint128`.",
      "- **`immutable`** for contract addresses (`registry`, `token`, `pool`, `manager`) — read from bytecode, not storage.",
      "- **`unchecked`** arithmetic where overflow is impossible (token balances after explicit checks).",
      "- **One-role-per-address** mapping (`mapping(address => Role)`) — a single SLOAD per access check.",
      "- **Infinite-allowance shortcut** in `transferFrom` skips an SSTORE when allowance is `type(uint256).max`.",
      "- **Evidence stored off-chain**: only a 32-byte `keccak256` hash goes on-chain; the text lives in the backend database.",
      "- **Events instead of on-chain history arrays** for the audit trail; the backend indexes them into SQLite.",
      "",
    ];
    fs.mkdirSync(path.join(__dirname, "..", "docs"), { recursive: true });
    fs.writeFileSync(path.join(__dirname, "..", "docs", "GAS_REPORT.md"), lines.join("\n"));
    console.table(rows.map((r) => ({ tx: r.label, estimate: Number(r.estimate), used: Number(r.used) })));
  });
});
